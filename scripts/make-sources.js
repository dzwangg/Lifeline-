// Writes meridian-city/sources.html, the page behind the panel's "Sources" link: every number in data/baselines.json,
// data/assumptions.json and data/resident-finance.json with its value, source and links, then the research notes in docs/sources.md.
// Usage: npm run sources   (tests/sources.test.js fails while the page is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const OUT = new URL('../meridian-city/sources.html', import.meta.url);
const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const URL_RE = /https?:\/\/[^\s<>"']+/g;
// A URL ends before trailing punctuation and any ")" it didn't open, so "(2021).pdf" stays whole and "(see https://x.org)" loses the ")".
const trimUrl = u => { u = u.replace(/[.,;:]+$/, ''); while (u.endsWith(')') && (u.match(/\(/g) ?? []).length < (u.match(/\)/g) ?? []).length) u = u.slice(0, -1).replace(/[.,;:]+$/, ''); return u; };
const links = text => [...new Set((String(text).match(URL_RE) ?? []).map(trimUrl))];
const withoutLinks = text => String(text).replace(URL_RE, u => u.slice(trimUrl(u).length)).replace(/\s+([,;.])/g, '$1').replace(/(\s*[,;]\s*)+$|\s{2,}/g, ' ').trim();
const linkList = urls => urls.map(u => `<a href="${esc(u)}">${esc(new URL(u).hostname.replace(/^www\./, ''))}</a>`).join(' · ');
const value = v => (Array.isArray(v) ? v.join(', ') : typeof v === 'object' ? Object.entries(v).map(([k, x]) => `${k} ${x}`).join(' · ') : v.toLocaleString('en-US', { maximumFractionDigits: 6 }));
const flag = source => /^(PLACEHOLDER|VERIFY)/.exec(source)?.[1];

// docs/sources.md: one note per "### " heading, with its "Source:" line and every link in it.
const notes = read('../docs/sources.md').split(/^### /m).slice(1).map(section => {
  const [heading, ...lines] = section.split('\n'), text = lines.join('\n').split(/^## /m)[0];
  const source = /\*\*Source:\*\*\s*(.+)/.exec(text)?.[1] ?? '';
  return { heading: heading.trim(), id: `note-${heading.split(':')[0].trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`, source: withoutLinks(source.replace(/\*+/g, '')), links: links(text) };
});
const noteFor = key => notes.find(n => n.heading.split(/[:\s]/)[0] === key);

function rows(entries) {
  return Object.entries(entries).map(([key, e]) => {
    const f = flag(e.source), note = noteFor(key), urls = links(`${e.source} ${e.alternate?.source ?? ''}`);
    return `<tr${f ? ' class="flagged"' : ''}>
  <th scope="row"><code>${esc(key)}</code></th>
  <td>${esc(value(e.value))}${e.unit ? ` <span class="unit">${esc(e.unit)}</span>` : ''}${e.year ? ` <span class="unit">(${e.year})</span>` : ''}</td>
  <td>${f ? `<span class="flag">${f}</span> ` : ''}${esc(withoutLinks(e.source.replace(/^(PLACEHOLDER|VERIFY)\s*-\s*/, '')))}${e.note ? `<p class="note">${esc(e.note)}</p>` : ''}${e.alternate ? `<p class="note">Alternate: ${esc(value(e.alternate.value))}. ${esc(withoutLinks(e.alternate.source))}</p>` : ''}${note ? `<p class="note"><a href="#${note.id}">Research note</a></p>` : ''}</td>
  <td>${linkList(urls)}</td>
</tr>`;
  }).join('\n');
}

const table = (title, path, entries) => `<h2>${title}</h2>
<p class="note"><code>${path}</code></p>
<div class="scroll"><table>
<thead><tr><th scope="col">Number</th><th scope="col">Value</th><th scope="col">Source</th><th scope="col">Links</th></tr></thead>
<tbody>
${rows(entries)}
</tbody>
</table></div>`;

export function renderSources() {
  const baselines = JSON.parse(read('../data/baselines.json')), assumptions = JSON.parse(read('../data/assumptions.json'));
  const finance = JSON.parse(read('../data/resident-finance.json'));
  const flagged = [baselines, assumptions, finance].flatMap(Object.values).filter(e => flag(e.source)).length;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Squidland sources</title>
<!-- Generated by scripts/make-sources.js from data/baselines.json, data/assumptions.json, data/resident-finance.json and docs/sources.md. Run npm run sources; don't edit by hand. -->
<style>
  :root { --ink: #0f3442; --muted: #42758a; --sodium: #078c9b; --line: #cfe7ec; --flag: #ffd75e; }
  body { margin: 0; padding: 24px 16px 48px; background: #f4fbfc; color: var(--ink); font: 15px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 1100px; margin: 0 auto; }
  h1 { margin: 0 0 6px; font-size: 26px; }
  h2 { margin: 32px 0 4px; font-size: 19px; }
  h3 { margin: 18px 0 2px; font-size: 15px; }
  a { color: var(--sodium); }
  code { font: 13px ui-monospace, SFMono-Regular, Menlo, monospace; overflow-wrap: anywhere; }
  .lede, .note { color: var(--muted); }
  .note { margin: 4px 0 0; font-size: 13px; }
  .scroll { overflow-x: auto; }
  table { width: 100%; border-collapse: collapse; font-size: 14px; }
  th, td { padding: 8px 10px 8px 0; border-bottom: 1px solid var(--line); text-align: left; vertical-align: top; }
  thead th { font-size: 12px; text-transform: uppercase; letter-spacing: .06em; color: var(--muted); }
  tbody th { font-weight: 400; min-width: 9em; }
  td:nth-child(2) { min-width: 8em; }
  td:nth-child(3) { min-width: 18em; }
  .unit { color: var(--muted); }
  .flag { display: inline-block; padding: 0 6px; border-radius: 4px; background: var(--flag); color: #4a3500; font: 600 11px ui-monospace, Menlo, monospace; letter-spacing: .06em; }
  tr.flagged th { box-shadow: inset 3px 0 0 #f0b400; padding-left: 8px; }
  .notes p { margin: 2px 0; }
</style>
</head>
<body>
<main>
<h1>Sources</h1>
<p class="lede">Every number the Squidland simulator takes from its data files, with its value, source and links. ${flagged} are marked <span class="flag">PLACEHOLDER</span> or <span class="flag">VERIFY</span>: not yet citable. <a href="./">Back to the simulator</a>.</p>
${table('Observed baselines', 'data/baselines.json', baselines)}
${table('Model assumptions', 'data/assumptions.json', assumptions)}
${table('Resident finances', 'data/resident-finance.json', finance)}
<h2>Research notes</h2>
<p class="note"><code>docs/sources.md</code>: proposed values and where they come from, researched for the entries above.</p>
<div class="notes">
${notes.map(n => `<section id="${n.id}">
<h3>${esc(n.heading)}</h3>
${n.source ? `<p>${esc(n.source)}</p>` : ''}
${n.links.length ? `<p class="note">${linkList(n.links)}</p>` : ''}
</section>`).join('\n')}
</div>
</main>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, renderSources());
  console.log('Wrote meridian-city/sources.html');
}
